import type { BetLeg, BetSlip, LegResult, RiskLevel } from '@/types';
import { deriveBetStatus } from '@/utils/stats';

interface SeedLeg {
  competition: string;
  competitionLabel?: string;
  home: string;
  away: string;
  market: string;
  selection: string;
  result: LegResult;
  score: string;
  odds?: number;
  note?: string;
  time?: string;
}

interface SeedSlip {
  title: string;
  competitionLabel: string;
  risk: RiskLevel;
  combinedOdds?: number;
  summary: string;
  notes?: string;
  sourceFile?: string;
  legs: SeedLeg[];
}

const competitionLabels: Record<string, string> = {
  CL: 'UEFA Champions League',
  EL: 'UEFA Europa League',
  UECL: 'UEFA Conference League',
  BL1: 'Bundesliga',
  SA: 'Serie A',
  PD: 'La Liga',
  DED: 'Eredivisie',
  ELC: 'EFL Championship',
};

function leg(date: string, legIndex: number, slipIndex: number, input: SeedLeg): BetLeg {
  const label = input.competitionLabel || competitionLabels[input.competition] || input.competition;
  return {
    id: `seed-${date}-${slipIndex}-${legIndex}`,
    kickoff: `${date}T${input.time ?? '20:00'}:00.000Z`,
    competition: input.competition,
    competitionLabel: label,
    homeTeam: input.home,
    awayTeam: input.away,
    market: input.market,
    selection: input.selection,
    odds: input.odds,
    result: input.result,
    score: input.score,
    note: input.note,
  };
}

function slip(date: string, index: number, input: SeedSlip): BetSlip {
  const legs = input.legs.map((item, legIndex) => leg(date, legIndex + 1, index, item));
  return {
    id: `seed-${date}-${index}`,
    date,
    title: input.title,
    competitionLabel: input.competitionLabel,
    risk: input.risk,
    status: deriveBetStatus(legs),
    combinedOdds: input.combinedOdds,
    stake: 1,
    legs,
    summary: input.summary,
    notes: input.notes,
    sourceFile: input.sourceFile,
    createdAt: `${date}T23:00:00.000Z`,
    updatedAt: `${date}T23:00:00.000Z`,
  };
}

function buildDay(date: string, sourceFile: string, slips: SeedSlip[]): BetSlip[] {
  return slips.map((item, index) => slip(date, index + 1, { ...item, sourceFile }));
}

