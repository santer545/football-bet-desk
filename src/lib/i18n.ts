const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, uk };

export type TranslationParams = Record<string, string | number>;

export function getLanguage(): Language {
  return useSettingsStore.getState().language;
}

export function getDateLocale(language: Language = getLanguage()): Locale {
  return DATE_LOCALES[language];
}

export function translate(
  language: Language,
  key: TranslationKey,
  params?: TranslationParams,
): string {
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

export function translateValidation(language: Language, message: string): string {
  const known = message as TranslationKey;
  if (known in dictionaries.en) return translate(language, known);
  return message;
}

export function pluralize(
  language: Language,
  count: number,
  ukForms: [one: string, few: string, many: string],
  enForms: [one: string, many: string],
): string {
  if (language === 'en') return count === 1 ? enForms[0] : enForms[1];
  const mod10 = Math.abs(count) % 10;
  const mod100 = Math.abs(count) % 100;
  if (mod10 === 1 && mod100 !== 11) return ukForms[0];
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return ukForms[1];
  return ukForms[2];
}

export function marketLabel(market: string, language: Language = getLanguage()): string {
  const map: Record<string, TranslationKey> = {
    'Double Chance': 'market.doubleChance',
    'Match Winner': 'market.matchWinner',
    'Total Goals': 'market.totalGoals',
    'Both Teams to Score': 'market.btts',
    'Draw No Bet': 'market.drawNoBet',
    'Win + Total': 'market.winTotal',
    Pass: 'market.pass',
  };
  const key = map[market];
  return key ? translate(language, key) : market;
}

export function selectionLabel(selection: string, language: Language = getLanguage()): string {
  const map: Record<string, TranslationKey> = {
    '1X (home side)': 'selection.homeSide',
    'X2 (away side)': 'selection.awaySide',
    'Home win': 'selection.homeWin',
    'Away win': 'selection.awayWin',
    'Over 2.5': 'selection.over25',
    'Under 3.5': 'selection.under35',
    Yes: 'selection.yes',
    No: 'selection.no',
    'No clear edge': 'selection.noEdge',
  };
  const key = map[selection];
  return key ? translate(language, key) : selection;
}

export function useTranslation() {
  const language = useSettingsStore((state) => state.language);
  const setLanguage = useSettingsStore((state) => state.setLanguage);

  const t = useCallback(
    (key: TranslationKey, params?: TranslationParams) => translate(language, key, params),
    [language],
  );

  const plural = useCallback(
    (
      count: number,
      ukForms: [one: string, few: string, many: string],
      enForms: [one: string, many: string],
    ) => pluralize(language, count, ukForms, enForms),
    [language],
  );

  return {
    language,
    setLanguage,
    t,
    plural,
    locale: DATE_LOCALES[language],
    formatMarket: (market: string) => marketLabel(market, language),
    formatSelection: (selection: string) => selectionLabel(selection, language),
  };
}
